#!/usr/bin/env node
/**
 * FinRL Trader V2 - static frontend build.
 *
 * The frontend is plain HTML/CSS/JS (no bundler, no npm dependencies), so the
 * "build" is a copy of `trader/frontend/` into the output directory plus
 * runtime configuration of the backend API origin.
 *
 * Environment variables (names only; values are written to `config.js`):
 *   API_BASE_URL  - Origin of the FastAPI backend, e.g. https://finrl.up.railway.app
 *                   Empty string (default) = same origin (self-hosted FastAPI).
 *
 * Output directory: `dist/` (override with `BUILD_OUTPUT_DIR`).
 * No network access and no third-party packages are required.
 */

"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "trader", "frontend");
const OUT = path.resolve(ROOT, process.env.BUILD_OUTPUT_DIR || "dist");

function copyDir(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, entry.name);
    const d = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDir(s, d);
    } else {
      fs.copyFileSync(s, d);
    }
  }
}

function main() {
  if (!fs.existsSync(SRC)) {
    console.error(`build_frontend: source directory not found: ${SRC}`);
    process.exit(1);
  }

  const apiBase = (process.env.API_BASE_URL || "").trim().replace(/\/+$/, "");
  if (apiBase && !/^https?:\/\//i.test(apiBase)) {
    console.error("build_frontend: API_BASE_URL must start with http:// or https://");
    process.exit(1);
  }

  // Guard against accidental same-origin production builds. An empty API base is
  // correct ONLY when the FastAPI backend serves this frontend itself. On a
  // separate host (Cloudflare Pages) it produces a dashboard whose API calls all
  // 404. Set ALLOW_SAME_ORIGIN=1 to acknowledge/self-host deliberately.
  const allowSameOrigin = ["1", "true", "yes"].includes(
    (process.env.ALLOW_SAME_ORIGIN || "").trim().toLowerCase()
  );
  if (!apiBase && !allowSameOrigin) {
    console.warn(
      "build_frontend: WARNING - API_BASE_URL is empty, so the dashboard will call\n" +
        "  its own origin. That only works when the backend serves this frontend\n" +
        "  (self-hosted). For Cloudflare Pages set API_BASE_URL to the Railway origin,\n" +
        "  e.g. API_BASE_URL=https://<project>.up.railway.app\n" +
        "  Set ALLOW_SAME_ORIGIN=1 to silence this warning."
    );
  }

  fs.rmSync(OUT, { recursive: true, force: true });
  copyDir(SRC, OUT);

  // Runtime configuration consumed by index.html -> app.js.
  fs.writeFileSync(
    path.join(OUT, "config.js"),
    "// Generated by scripts/build_frontend.js - do not edit by hand.\n" +
      `window.FINRL_API_BASE_URL = ${JSON.stringify(apiBase)};\n`,
    "utf8"
  );

  // Tighten connect-src to the actual API origin. The checked-in _headers keeps
  // https: as a manual-deploy fallback, but a generated bundle should not be
  // allowed to exfiltrate to an arbitrary HTTPS host.
  const headersPath = path.join(OUT, "_headers");
  if (fs.existsSync(headersPath)) {
    const connectSrc = apiBase ? `'self' ${new URL(apiBase).origin}` : "'self'";
    const headers = fs.readFileSync(headersPath, "utf8").replace(
      /connect-src 'self' https:;/,
      `connect-src ${connectSrc};`
    );
    fs.writeFileSync(headersPath, headers, "utf8");
  }

  console.log(`build_frontend: wrote ${path.relative(ROOT, OUT)} (API_BASE_URL=${apiBase || "<same origin>"})`);
}

main();
